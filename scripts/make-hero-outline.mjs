// Traces the outline of the hero ornament (round face + hanging tab, with the
// hole cut out) from its product photo. The outline is used twice:
//   - public/products/peace-on-earth-mask.svg masks the static <img>, hiding
//     the photo's own white backdrop and twine;
//   - src/hero-outline.js is the shape the WebGL ornament is extruded from.
// Both come from the same numbers, so the static and 3D views line up.
//
//   node scripts/make-hero-outline.mjs
//
// The circle fits below were measured from peace-on-earth.webp. If the photo
// is replaced, re-measure them (the tab and the bottom of the face are the
// only parts not traced pixel by pixel).

import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PHOTO = join(ROOT, 'public/products/peace-on-earth.webp');

// The rounded top of the tab is hidden under the photo's twine, so it comes
// from a circle fitted to the rows just below it. The hole is concentric.
const TAB = { x: 622, y: 146, r: 73 };
const HOLE = { x: 622, y: 146, r: 28 };
// The last few rows of the face are drawn from its circle so it closes round.
const FACE = { x: 622, y: 654, r: 480 };
const TRACE_FROM = 88; // first row where the tab is wider than the twine
const TRACE_TO = 1110;
const STEP = 2;

const { data, info } = await sharp(PHOTO).removeAlpha().raw().toBuffer({ resolveWithObject: true });
const { width: W } = info;
const px = (x, y) => {
  const i = (y * W + x) * 3;
  return [data[i], data[i + 1], data[i + 2]];
};
const bg = px(2, 2);
const isWood = (x, y) => {
  const [r, g, b] = px(x, y);
  return Math.hypot(r - bg[0], g - bg[1], b - bg[2]) > 40;
};

function extents(y) {
  let left = -1;
  let right = -1;
  for (let x = 0; x < W; x++) {
    if (isWood(x, y)) {
      if (left < 0) left = x;
      right = x;
    }
  }
  return [left, right];
}

const circleRow = (c, y) => {
  const h = Math.sqrt(Math.max(0, c.r * c.r - (c.y - y) ** 2));
  return [c.x - h, c.x + h];
};

const rows = [];
for (let y = TAB.y - TAB.r; y < TRACE_FROM; y += 1) rows.push([y, ...circleRow(TAB, y)]);
for (let y = TRACE_FROM; y <= TRACE_TO; y += STEP) rows.push([y, ...extents(y)]);
for (let y = TRACE_TO + STEP; y <= FACE.y + FACE.r; y += 1) rows.push([y, ...circleRow(FACE, y)]);

// Smooth the traced edges a little so pixel noise does not show as facets.
const traced = rows.map(([y]) => y >= TRACE_FROM && y <= TRACE_TO);
const smooth = rows.map((row, i) => {
  if (!traced[i]) return row;
  let l = 0;
  let r = 0;
  let n = 0;
  for (let k = -2; k <= 2; k++) {
    const j = i + k;
    if (j < 0 || j >= rows.length || !traced[j]) continue;
    l += rows[j][1];
    r += rows[j][2];
    n++;
  }
  return [row[0], l / n, r / n];
});

const round = (v) => Math.round(v * 10) / 10;
// Down the left side, then back up the right side.
const points = [
  ...smooth.map(([y, l]) => [round(l), y]),
  ...[...smooth].reverse().map(([y, , r]) => [round(r + 1), y]),
];

const d =
  'M' + points.map(([x, y]) => `${x} ${y}`).join('L') + 'Z' +
  `M${HOLE.x - HOLE.r} ${HOLE.y}a${HOLE.r} ${HOLE.r} 0 1 0 ${2 * HOLE.r} 0a${HOLE.r} ${HOLE.r} 0 1 0 ${-2 * HOLE.r} 0Z`;

await writeFile(
  join(ROOT, 'public/products/peace-on-earth-mask.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${W}"><path fill-rule="evenodd" d="${d}"/></svg>\n`,
);

await writeFile(
  join(ROOT, 'src/hero-outline.js'),
  `// Generated by scripts/make-hero-outline.mjs from public/products/peace-on-earth.webp.
// Photo pixel coordinates (y down) of the ornament's outline, its hanging hole,
// and the top of the tab, where the drawn twine meets the wood.
export const HERO_OUTLINE = {
  size: ${W},
  tabTop: ${TAB.y - TAB.r},
  hole: { x: ${HOLE.x}, y: ${HOLE.y}, r: ${HOLE.r} },
  face: { x: ${FACE.x}, y: ${FACE.y}, r: ${FACE.r} },
  points: [${points.map(([x, y]) => `${x},${y}`).join(',')}],
};
`,
);

console.log(`outline: ${points.length} points; hole r=${HOLE.r}; tab top y=${TAB.y - TAB.r}`);
